export const STRINGS: Record<Lang, Record<StringKey, string>> = { en, ar };

export function translate(lang: Lang, key: StringKey, params?: Record<string, string | number>): string {
  let s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  }
  return s;
}

export const isRTLLang = (lang: Lang) => lang === 'ar';

/**
 * Text alignment that respects the chosen language on web and native.
 * expo-localization is configured with supportsRTL:false, so the native
 * I18nManager stays LTR and we flip layout ourselves with `direction` styles.
 * The swap guard keeps it correct even if a device ever forces RTL.
 */
export function textAlignFor(lang: Lang): TextStyle['textAlign'] {
  const wantRTL = isRTLLang(lang);
  const nativeSwaps = Platform.OS !== 'web' && I18nManager.isRTL;
  const effectiveRight = nativeSwaps ? !wantRTL : wantRTL;
  return effectiveRight ? 'right' : 'left';
}

// ---- Numbers written in words (for the parental gate) ----
const EN_ONES = ['', 'one', 'two', 'three', 'four', 'five', 'six', 'seven', 'eight', 'nine'];
const EN_TENS = ['', 'ten', 'twenty', 'thirty', 'forty', 'fifty', 'sixty', 'seventy', 'eighty', 'ninety'];
const AR_ONES = ['', 'واحد', 'اثنان', 'ثلاثة', 'أربعة', 'خمسة', 'ستة', 'سبعة', 'ثمانية', 'تسعة'];
const AR_TENS = ['', 'عشرة', 'عشرون', 'ثلاثون', 'أربعون', 'خمسون', 'ستون', 'سبعون', 'ثمانون', 'تسعون'];

/** n in 21..99 */
export function numberInWords(n: number, lang: Lang): string {
  const tens = Math.floor(n / 10);
  const ones = n % 10;
  if (lang === 'ar') {
    if (ones === 0) return AR_TENS[tens];
    return `${AR_ONES[ones]} و${AR_TENS[tens]}`;
  }
  if (ones === 0) return EN_TENS[tens];
  return `${EN_TENS[tens]}-${EN_ONES[ones]}`;
}

/** Converts Arabic-Indic and Persian digits to 0-9. */
export function normalizeDigits(s: string): string {
  return s
    .replace(/[٠-٩]/g, (d) => String(d.charCodeAt(0) - 0x0660))
    .replace(/[۰-۹]/g, (d) => String(d.charCodeAt(0) - 0x06f0));
}
